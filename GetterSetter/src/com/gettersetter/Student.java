package com.gettersetter;

public class Student {

		private int rno;
		private String name;
		private float marks;
		private long contact;
		private boolean flag;
		private int age;
		private char division;
		private double fees;
		
		public int getRno()
		{
			return rno;
		}
		public void setRno(int i)
		{
			rno=i;
		}
		
		public String getName()
		{
			return name;
		}
		
		public void setName(String s)
		{
			name=s;
		}
		public float getMarks() 
		{
			return marks;
		}
		public void setMarks(float marks1) 
		{
			marks = marks1;
		}
		public long getContact() {
			return contact;
		}
		public void setContact(long contact1)
		{
			contact = contact1;
		}
		public boolean getFlag() {
			
			return flag;
		}
		public void setFlag(boolean flag1) 
		{
			flag = flag1;
		}
		public int getAge()
		{
			return age;
		}
		public void setAge(int age1)
		{
			age = age1;
		}
		public char getDivision() 
		{
			return division;
		}
		public void setDivision(char division1)
		{
			division = division1;
		}
		public double getFees() 
		{
			return fees;
		}
		public void setFees(double fees1)
		{
			fees = fees1;
		}
		
		
		
	}


